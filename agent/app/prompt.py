"""Сборка промпта для LLM-суммаризации алерта. Чистые функции."""
from __future__ import annotations

from .context import IncidentContext
from .webhook import Alert, format_raw_group

SYSTEM_PROMPT = """\
Ты — дежурный SRE-ассистент домашней лаборатории. Ты получаешь сработавший \
алерт мониторинга (Prometheus) и живые метрики на момент инцидента.

Твоя задача — объяснить инцидент администратору на русском языке, коротко и \
по делу, без общих слов. Ответь СТРОГО в трёх разделах с такими заголовками:

ЧТО СЛУЧИЛОСЬ:
<1–2 предложения: что означает алерт, в момент чего это происходит>

ВЕРОЯТНАЯ ПРИЧИНА:
<конкретная гипотеза на основе метрик и лейблов; если данных мало — честно \
напиши, чего не хватает>

ЧТО ПРОВЕРИТЬ:
<2–4 конкретных действия или команды (bash/docker), в порядке приоритета>

Не выдумывай значения, которых нет в данных. Не используй markdown-заголовки \
и таблицы, только указанные заголовки разделов и обычный текст со списками.
"""

USER_TEMPLATE = """\
Сработавшие алерты (сырой вид, как их видит Alertmanager):

{raw_alerts}

Живые метрики на момент инцидента:

{context}
"""


def build_user_prompt(alerts: list[Alert], context: IncidentContext) -> str:
    return USER_TEMPLATE.format(
        raw_alerts=format_raw_group(alerts),
        context=context.render(),
    )
